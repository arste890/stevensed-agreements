# frozen_string_literal: true

describe 'E-signature settings' do
  let(:account) { create(:account) }
  let(:user) { create(:user, account:) }

  before do
    EncryptedConfig.create!(account:, key: EncryptedConfig::ESIGN_CERTS_KEY,
                            value: GenerateCertificate.call.transform_values(&:to_pem))
    sign_in(user)
  end

  context 'when Vault signing is enabled' do
    before { allow(Stevensed::VaultSigning).to receive(:enabled?).and_return(true) }

    it 'lists the StevensED chain in use and marks the autogenerated certificate retired' do
      get settings_esign_path

      body = response.body
      leaf = Stevensed::CertificateSummary.call(Stevensed::VaultSigning.certificate)

      expect(response).to have_http_status(:ok)
      expect(body).to include('StevensED signing certificate')
      expect(body).to include('Oracle Cloud Vault hardware security module and is not exportable')
      leaf_index = body.index('<h3 class="se-row__title">StevensED Agreements</h3>')
      expect(leaf_index).to be < body.index('<h3 class="se-row__title">StevensED Document Signing CA</h3>')
      expect(body).to include('StevensED Root CA', 'RSA 3072-bit', 'ECDSA P-384', leaf.fingerprint.split(':').join(':<wbr>'))
      expect(body).to include('Retired: kept to verify documents signed before November 26, 2026')
      expect(body).not_to include('Make default')
      expect(body).not_to include('PRIVATE KEY')
    end

    it 'does not make the autogenerated certificate the default again' do
      put settings_esign_path, params: { name: EsignSettingsController::DEFAULT_CERT_NAME }

      expect(response).to redirect_to(settings_esign_path)
      expect(EncryptedConfig.find_by(account:, key: EncryptedConfig::ESIGN_CERTS_KEY).value['custom']).to be_blank
    end
  end

  context 'when Vault signing is not enabled' do
    before { allow(Stevensed::VaultSigning).to receive(:enabled?).and_return(false) }

    it 'shows the autogenerated certificate as the default and no Vault section' do
      get settings_esign_path

      expect(response.body).to include(EsignSettingsController::DEFAULT_CERT_NAME, 'Default')
      expect(response.body).not_to include('StevensED signing certificate')
      expect(response.body).not_to include('Retired:')
    end
  end
end
